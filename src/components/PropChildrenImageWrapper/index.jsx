import React from 'react'
import styles from './ImageWrapper.module.sass'

// всі пропси як параметри ми витягуємо якщо вони нам потрібні на місці, 
// всі інші атрибути можна зібратив  рест пропси(параметри) як у звичайних функціях
function ImageWrapper({width, height, children, ...restProps}) {

    // порписуєм додаткові інлайн стилі (завжди обєкт) якщо нам наприклад треба додатково керувати компонентом
    const wrapperDimentions = {
        width,  // = width:width - форма скороченого запису якщо назви однакові ключа і змінної властивості можна просто прописати одинм словом
        height,  // = height:height
    }
    console.log(restProps);  //  {title='image' tabIndex={1}}

    // {...restProps} - прокидання пропсів
    // ми збираємо всі атрибути які не потрібно явно вказувати в рестПропси і в атрибутах же їх
    // і розпаковуємо/розширюємо зібраний обєкт перетвориться у відповідні атрибути і пропишеться як треба
    // в пари ключ='значення'
    // Також має значення де саме ми його розширимо першим чи останнім, якщо наприклад в рестПропси потраплять 
    // якість стилі і ми розширимо його останнім атрибутом то ті стилі які в ньому містяться перебють всі ті що були
    // застосовані перед цим на початку атрибутів. Треба бути обережним і розуміти в якому порядку його потрібно використовувати
    // в кожній окремій ситуації
  return (
    <div style={wrapperDimentions} className={styles.imageContainer} {...restProps}>{children}</div>
  )
}

export default ImageWrapper